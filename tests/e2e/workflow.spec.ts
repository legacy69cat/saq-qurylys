import { expect, test } from "./fixtures";
test("new publication → manual review → updated score → signal versions → print", async ({ page }, testInfo) => {
    const errors: string[] = [];
    page.on("pageerror", (error) => errors.push(error.message));
    await page.goto("/projects/demo-g");
    await expect(page.locator(".detail-score")).toContainText("35");
    await page.getByText("Добавить публикацию вручную", { exact: true }).click();
    const add = page.getByRole("form", { name: "Сохранить публикацию", exact: true });
    await add.getByLabel("Площадка", { exact: true }).fill("Тестовая площадка");
    await add.getByLabel("Аккаунт / источник").fill("demo_e2e");
    await add.getByLabel("Ссылка на публикацию").fill("https://example.invalid/new-e2e");
    await add.getByLabel("Дата публикации").fill("2026-10-14");
    await add.getByLabel("Текст публикации").fill("Контур 07 строится. Внесите депозит 300 000 ₸ за квартиру.");
    await add.getByLabel("Автор решения").fill("Демо-тестировщик");
    await add.getByRole("button", { name: "Сохранить публикацию", exact: true }).click();
    const publication = page.locator(".publication-card").filter({ hasText: "Тестовая площадка" });
    await expect(publication).toContainText("demo_e2e");
    await expect(page.locator(".detail-score")).toContainText("35");
    await publication.getByText("Анализировать публикацию с ИИ", { exact: true }).click();
    const ai = publication.getByRole("form", { name: "Запустить ИИ-анализ", exact: true });
    await ai.getByLabel("Автор решения").fill("Демо-тестировщик");
    await ai.getByRole("button").click();
    await expect(ai.getByRole("alert")).toContainText("ИИ не настроен");
    await expect(publication).toContainText("Внесите депозит 300 000 ₸");
    await publication.getByText("Добавить гипотезу вручную", { exact: true }).click();
    const manual = publication.getByRole("form", { name: "Сохранить ручную гипотезу", exact: true });
    for (const [code, quote, score] of [["R2", "Внесите депозит 300 000 ₸", "60"], ["R3", "Контур 07 строится.", "70"]]) {
        await manual.getByRole("combobox", { name: "Фактор", exact: true }).selectOption(code);
        await manual.getByLabel("Дословная цитата").fill(quote);
        await manual.getByLabel("Объяснение").fill("Признак подтверждён сохранённым текстом.");
        await manual.getByLabel("Автор решения").fill("Демо-тестировщик");
        await manual.getByRole("button").click();
        const hypothesis = publication.locator(".hypothesis").filter({ has: page.getByRole("heading", { name: new RegExp(`^${code} ·`) }) });
        await expect(hypothesis).toContainText(quote);
        await hypothesis.getByRole("combobox", { name: "Решение", exact: true }).selectOption("confirmed");
        await hypothesis.getByLabel("Автор решения").fill("Демо-аналитик");
        await hypothesis.getByRole("button", { name: "Сохранить решение по гипотезе" }).click();
        await expect(page.locator(".detail-score")).toContainText(score);
    }
    await expect(page.locator(".detail-score")).toContainText("Красная");
    const create = page.getByRole("form", { name: "Создать сигнальную карточку", exact: true });
    await create.getByLabel("Автор решения").fill("Автор сигнала");
    await create.getByRole("button").click();
    await expect(page).toHaveURL(/\/signals\//);
    await expect(page.getByRole("heading", { name: "Сигнальная карточка", exact: true })).toBeVisible();
    await expect(page.locator("main")).toContainText("Версия 1");
    const review = page.getByRole("form", { name: "Сохранить решение по сигналу", exact: true });
    await review.getByRole("combobox", { name: "Решение", exact: true }).selectOption("returned");
    await review.getByLabel("Автор решения").fill("Проверяющий");
    await review.getByRole("button").click();
    await expect(review.getByRole("alert")).toContainText("Причина возврата");
    await review.getByRole("combobox", { name: "Решение", exact: true }).selectOption("returned");
    await review.getByLabel("Комментарий (обязателен при возврате)").fill("Повторно проверить источник");
    await review.getByLabel("Автор решения").fill("Проверяющий");
    await review.getByRole("button").click();
    await expect(page.locator("main")).toContainText("Возвращён на доработку");
    await page.getByRole("form", { name: "Создать сигнальную карточку", exact: true }).getByLabel("Автор решения").fill("Автор сигнала");
    await page.getByRole("button", { name: "Создать сигнальную карточку", exact: true }).click();
    await expect(page.locator("main")).toContainText("Версия 2");
    await review.getByRole("combobox", { name: "Решение", exact: true }).selectOption("confirmed");
    await review.getByLabel("Автор решения").fill("Проверяющий");
    await review.getByRole("button").click();
    await expect(page.locator("dd").filter({ hasText: /^Подтверждён$/ })).toBeVisible();
    await page.reload();
    await expect(page.locator("main")).toContainText("Проверяющий");
    await page.emulateMedia({ media: "print" });
    await expect(page.getByRole("button", { name: "Печать / сохранить PDF" })).toBeHidden();
    await expect(page.getByRole("heading", { name: "Сигнальная карточка", exact: true })).toBeVisible();
    await page.pdf({ path: testInfo.outputPath("signal.pdf"), printBackground: true });
    await page.screenshot({ path: testInfo.outputPath("signal-print.png"), fullPage: true });
    expect(errors).toEqual([]);
});
test("official sources and unknown legal basis preserve conservative scoring", async ({ page }) => {
    await page.goto("/sources");
    await expect(page.getByRole("link", { name: "E-License ↗", exact: true })).toHaveAttribute("href", "https://elicense.kz");
    await expect(page.locator("main")).toContainText("не доказывает отсутствие");
    await page.goto("/projects/demo-g");
    await page.getByText("Сохранить результат ручной проверки", { exact: true }).click();
    const form = page.getByRole("form", { name: "Сохранить проверку основания", exact: true });
    await form.getByRole("combobox", { name: "Результат", exact: true }).selectOption("unknown");
    await form.getByLabel("Источник проверки").fill("Учебный реестр");
    await form.getByLabel("Ссылка на материал").fill("https://example.invalid/check");
    await form.getByLabel("Результат и основания вывода").fill("Источник недоступен, основание не установлено.");
    await form.getByLabel("Автор решения").fill("Демо-аналитик");
    await form.getByRole("button").click();
    await expect(page.locator(".detail-score")).toContainText("0");
    await expect(page.getByText("Проверка основания: Демо-аналитик", { exact: false })).toBeVisible();
});
